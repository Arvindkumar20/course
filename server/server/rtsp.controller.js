// Create camera
router.post("", async (req, res, next) => {
  try {
    const name = typeof req.body.name === "string" ? req.body.name.trim() : "";

    if (!name || name.length > 100) {
      return res.status(400).json({
        error: "Camera name is required (maximum 100 characters)",
      });
    }

    let sourceUrl;

    try {
      sourceUrl = validateSourceUrl(req.body.sourceUrl);
    } catch (error) {
      return res.status(400).json({ error: error.message });
    }

    const camera = await Camera.create({
      name,
      streamPath: `cam_${crypto.randomBytes(16).toString("hex")}`,
      sourceUrl,
      enabled: true,
    });

    try {
      await addMediaMTXPath(camera.streamPath, sourceUrl);
    } catch (error) {
      // Roll back the database record if MediaMTX rejects the path.
      await Camera.findByIdAndDelete(camera._id);

      console.error("Failed to configure MediaMTX:", error.message);

      return res.status(502).json({
        error: "Could not configure this camera in MediaMTX.",
      });
    }

    return res.status(201).json(publicCamera(camera));

    return res.status(201).json(publicCamera(camera));
  } catch (error) {
    next(error);
  }
});

// List cameras without revealing original RTSP credentials
router.get("", async (req, res, next) => {
  try {
    const cameras = await Camera.find()
      .select("name streamPath enabled createdAt")
      .sort({ createdAt: -1 })
      .lean();

    return res.json(cameras.map(publicCamera));
  } catch (error) {
    next(error);
  }
});

// Enable or disable a camera
router.patch("/:cameraId/enabled", async (req, res, next) => {
  try {
    if (typeof req.body.enabled !== "boolean") {
      return res.status(400).json({
        error: "enabled must be a boolean",
      });
    }

    const camera = await Camera.findByIdAndUpdate(
      req.params.cameraId,
      { enabled: req.body.enabled },
      { new: true, runValidators: true },
    );

    if (!camera) {
      return res.status(404).json({ error: "Camera not found" });
    }

    return res.json(publicCamera(camera));
  } catch (error) {
    next(error);
  }
});

// Update camera name or source URL
router.patch("/:cameraId/enabled", async (req, res, next) => {
  try {
    if (typeof req.body.enabled !== "boolean") {
      return res.status(400).json({
        error: "enabled must be a boolean",
      });
    }

    const camera = await Camera.findById(req.params.cameraId)
      .select("+sourceUrl");

    if (!camera) {
      return res.status(404).json({ error: "Camera not found" });
    }

    if (req.body.enabled) {
      await addMediaMTXPath(camera.streamPath, camera.sourceUrl);
    } else {
      await deleteMediaMTXPath(camera.streamPath);
    }

    camera.enabled = req.body.enabled;
    await camera.save();

    return res.json(publicCamera(camera));
  } catch (error) {
    next(error);
  }
});

// Delete camera
router.delete("/:cameraId", async (req, res, next) => {
  try {
    const camera = await Camera.findById(req.params.cameraId);

    if (!camera) {
      return res.status(404).json({ error: "Camera not found" });
    }

    await deleteMediaMTXPath(camera.streamPath);
    await Camera.findByIdAndDelete(camera._id);

    return res.json({
      success: true,
      message: "Camera deleted",
      id: camera._id.toString(),
    });
  } catch (error) {
    next(error);
  }
});
export const RTSPRouter = router;
