const cameraSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
      maxlength: 100,
    },
    streamPath: {
      type: String,
      required: true,
      unique: true,
      immutable: true,
    },
    sourceUrl: {
      type: String,
      required: true,
      select: false,
    },
    enabled: {
      type: Boolean,
      default: true,
    },
  },
  { timestamps: true },
);

const Camera = mongoose.model("Camera", cameraSchema);

function validateSourceUrl(value) {
  if (typeof value !== "string" || value.length > 2048) {
    throw new Error("A valid RTSP source URL is required");
  }

  let url;

  try {
    url = new URL(value);
  } catch {
    throw new Error("Invalid RTSP URL");
  }

  if (!["rtsp:", "rtsps:"].includes(url.protocol)) {
    throw new Error("Only rtsp:// and rtsps:// sources are supported");
  }

  if (!url.hostname || url.hash) {
    throw new Error("Invalid RTSP source URL");
  }

  return url.toString();
}

function authenticateAdmin(req, res, next) {
  const supplied = req.get("x-api-key") || "";
  const a = Buffer.from(supplied);
  const b = Buffer.from(ADMIN_KEY);

  if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) {
    return res.status(401).json({ error: "Unauthorized" });
  }

  next();
}

function publicCamera(camera) {
  return {
    id: camera._id.toString(),
    name: camera.name,
    streamPath: camera.streamPath,
    enabled: camera.enabled,
    createdAt: camera.createdAt,
    rtspUrl: `rtsp://${PUBLIC_HOST}:8554/${camera.streamPath}`,
    hlsUrl: `${HLS_PROTOCOL}://${PUBLIC_HOST}:8888/${camera.streamPath}/index.m3u8`,
    webrtcUrl: `${HLS_PROTOCOL}://${PUBLIC_HOST}:8889/${camera.streamPath}`,
  };
}

const MEDIAMTX_API_URL = (
  process.env.MEDIAMTX_API_URL || "http://127.0.0.1:9997"
).replace(/\/+$/, "");

async function mediaMTXRequest(method, endpoint, payload, allow404 = false) {
  const response = await fetch(`${MEDIAMTX_API_URL}${endpoint}`, {
    method,
    headers: payload ? { "Content-Type": "application/json" } : {},
    ...(payload ? { body: JSON.stringify(payload) } : {}),
  });

  if (response.status === 404 && allow404) {
    return 404;
  }

  if (!response.ok) {
    // Do not log RTSP credentials or the complete source URL.
    throw new Error(`MediaMTX API request failed: HTTP ${response.status}`);
  }

  return response.status;
}

function mediaMTXPathConfig(sourceUrl) {
  return {
    source: sourceUrl,
    sourceOnDemand: true,
    sourceOnDemandStartTimeout: "15s",
    sourceOnDemandCloseAfter: "10s",
  };
}

async function addMediaMTXPath(streamPath, sourceUrl) {
  await mediaMTXRequest(
    "POST",
    `/v3/config/paths/add/${encodeURIComponent(streamPath)}`,
    mediaMTXPathConfig(sourceUrl),
  );
}

async function deleteMediaMTXPath(streamPath) {
  await mediaMTXRequest(
    "DELETE",
    `/v3/config/paths/delete/${encodeURIComponent(streamPath)}`,
    undefined,
    true, // A missing path is okay when deleting.
  );
}

async function replaceMediaMTXPath(streamPath, sourceUrl) {
  const result = await mediaMTXRequest(
    "POST",
    `/v3/config/paths/replace/${encodeURIComponent(streamPath)}`,
    mediaMTXPathConfig(sourceUrl),
    true,
  );

  // If the path hasn't been configured yet, create it.
  if (result === 404) {
    await addMediaMTXPath(streamPath, sourceUrl);
  }
}

