router.get("/stream-configs/:streamPath", async (req, res, next) => {
  try {
    const { streamPath } = req.params;

    // Only accept paths generated by this application.
    if (!/^cam_[a-f0-9]{32}$/.test(streamPath)) {
      return res.sendStatus(404);
    }

    const camera = await Camera.findOne({
      streamPath,
      enabled: true,
    }).select("+sourceUrl");

    if (!camera) {
      return res.sendStatus(404);
    }

    router.set("Cache-Control", "no-store");

    return res.json({
      source: camera.sourceUrl,
      sourceOnDemand: true,
      sourceOnDemandStartTimeout: "15s",
      sourceOnDemandCloseAfter: "10s",
    });
  } catch (error) {
    next(error);
  }
});

